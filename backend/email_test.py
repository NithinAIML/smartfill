#!/usr/bin/env python3
"""
Complete Email Test Script for SMARTFILL AI
This script will test and fix the email functionality
"""

import os
import sys
import traceback
import tempfile
from datetime import datetime

# Add current directory to path
sys.path.append(os.path.dirname(os.path.abspath(__file__)))

def create_test_document():
    """Create a test Word document"""
    try:
        from docx import Document
        from docx.shared import Pt
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        
        # Create document
        doc = Document()
        
        # Add SMARTFILL AI heading
        heading = doc.add_heading('SMARTFILL AI', 0)
        heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
        
        # Add caption
        caption = doc.add_paragraph('AI based RFP smart filling solution')
        caption.alignment = WD_ALIGN_PARAGRAPH.CENTER
        caption_format = caption.runs[0].font
        caption_format.size = Pt(14)
        caption_format.italic = True
        
        # Add separator
        doc.add_paragraph('=' * 60).alignment = WD_ALIGN_PARAGRAPH.CENTER
        
        # Add generation timestamp
        timestamp = doc.add_paragraph(f'Generated on: {datetime.now().strftime("%B %d, %Y at %I:%M %p")}')
        timestamp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        timestamp.runs[0].font.size = Pt(10)
        
        doc.add_paragraph()  # Empty line
        
        # Add test questions and answers
        test_qa = [
            ("What is SMARTFILL AI?", "SMARTFILL AI is an advanced RFP processing solution that uses artificial intelligence to automatically generate responses to RFP questions."),
            ("How does the system work?", "The system analyzes uploaded training documents, extracts knowledge, and uses that knowledge to provide accurate answers to RFP questions."),
            ("What are the main benefits?", "Key benefits include time savings, improved accuracy, consistency in responses, and the ability to handle large volumes of RFPs efficiently.")
        ]
        
        for i, (question, answer) in enumerate(test_qa, 1):
            # Question
            q_paragraph = doc.add_paragraph()
            q_run = q_paragraph.add_run(f"Question {i}: {question}")
            q_run.font.bold = True
            q_run.font.size = Pt(12)
            
            # Answer
            a_paragraph = doc.add_paragraph()
            a_run = a_paragraph.add_run(f"Answer: {answer}")
            a_run.font.size = Pt(11)
            
            # Add space between Q&A pairs
            doc.add_paragraph()
        
        # Footer
        doc.add_page_break()
        footer_para = doc.add_paragraph()
        footer_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        footer_run = footer_para.add_run("Generated by SMARTFILL AI\\nAI based RFP smart filling solution")
        footer_run.font.size = Pt(10)
        footer_run.font.italic = True
        
        # Save to temporary file
        temp_dir = tempfile.gettempdir()
        doc_filename = f"SMARTFILL_AI_Test_{datetime.now().strftime('%Y%m%d_%H%M%S')}.docx"
        doc_path = os.path.join(temp_dir, doc_filename)
        doc.save(doc_path)
        
        print(f"✅ Test document created: {doc_path}")
        print(f"   File size: {os.path.getsize(doc_path)} bytes")
        return doc_path
        
    except Exception as e:
        print(f"❌ Document creation failed: {e}")
        traceback.print_exc()
        return None

def send_test_email():
    """Send a test email with the document"""
    try:
        # Import configuration
        from config import settings
        
        print("🧪 Testing Email Configuration...")
        print(f"   SMTP Server: {settings.SMTP_SERVER}:{settings.SMTP_PORT}")
        print(f"   Username: {settings.SMTP_USERNAME}")
        print(f"   Sender: {settings.SENDER_EMAIL}")
        
        # Check if email is configured
        if not settings.SMTP_USERNAME or not settings.SMTP_PASSWORD or not settings.SENDER_EMAIL:
            print("❌ Email not properly configured!")
            print("   Required environment variables:")
            print("   - SMTP_USERNAME (your Gmail address)")
            print("   - SMTP_PASSWORD (your app password)")
            print("   - SENDER_EMAIL (same as SMTP_USERNAME)")
            return False
        
        # Create test document
        doc_path = create_test_document()
        if not doc_path:
            print("❌ Cannot proceed without document")
            return False
        
        # Send email
        import smtplib
        from email.mime.text import MIMEText
        from email.mime.multipart import MIMEMultipart
        from email.mime.application import MIMEApplication
        import mimetypes
        
        # Email content
        recipient = settings.SMTP_USERNAME  # Send to yourself for testing
        subject = "SMARTFILL AI - Email Functionality Test"
        body = f"""
Dear User,

This is a test email from SMARTFILL AI to verify that the email functionality is working correctly.

Test Details:
- Generated on: {datetime.now().strftime('%B %d, %Y at %I:%M %p')}
- Document attached: {os.path.basename(doc_path)}
- System: SMARTFILL AI Email System

If you receive this email with the attached Word document, the email functionality is working perfectly!

Best regards,
SMARTFILL AI Team

---
SMARTFILL AI - AI based RFP smart filling solution
        """
        
        print(f"\\n📧 Sending test email...")
        print(f"   To: {recipient}")
        print(f"   Subject: {subject}")
        print(f"   Attachment: {os.path.basename(doc_path)}")
        
        # Create message
        msg = MIMEMultipart()
        msg["From"] = settings.SENDER_EMAIL
        msg["To"] = recipient
        msg["Subject"] = subject
        msg.attach(MIMEText(body.strip(), "plain"))
        
        # Add attachment
        if os.path.exists(doc_path):
            ctype, _ = mimetypes.guess_type(doc_path)
            subtype = (ctype.split("/", 1)[1] if ctype else "octet-stream")
            with open(doc_path, "rb") as f:
                part = MIMEApplication(f.read(), _subtype=subtype)
            part.add_header("Content-Disposition", "attachment", filename=os.path.basename(doc_path))
            msg.attach(part)
            print(f"   ✅ Attachment added: {os.path.basename(doc_path)}")
        
        # Send email
        with smtplib.SMTP(settings.SMTP_SERVER, settings.SMTP_PORT, timeout=30) as server:
            print("   🔐 Starting TLS...")
            server.starttls()
            
            print("   🔑 Logging in...")
            server.login(settings.SMTP_USERNAME, settings.SMTP_PASSWORD)
            
            print("   📤 Sending message...")
            server.send_message(msg)
        
        print("\\n✅ EMAIL SENT SUCCESSFULLY!")
        print(f"   Check your inbox: {recipient}")
        print(f"   Subject: {subject}")
        
        # Cleanup
        try:
            os.remove(doc_path)
            print(f"   🧹 Cleaned up: {os.path.basename(doc_path)}")
        except:
            pass
            
        return True
        
    except Exception as e:
        print(f"\\n❌ Email sending failed: {e}")
        traceback.print_exc()
        return False

def main():
    """Run the email test"""
    print("🚀 SMARTFILL AI Email Test")
    print("=" * 50)
    
    success = send_test_email()
    
    print("\\n" + "=" * 50)
    if success:
        print("✅ EMAIL TEST PASSED!")
        print("   The email functionality is working correctly.")
        print("   Check your email inbox for the test message.")
    else:
        print("❌ EMAIL TEST FAILED!")
        print("   Please check the error messages above.")
    
if __name__ == "__main__":
    main()
